"""Regenerate paper/results_table.tex from results/*.json -- run this after each locus
finishes rather than hand-transcribing numbers into main.tex, so the paper's table can
never drift from what the pipeline actually produced.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(os.path.dirname(HERE), "results")
OUT_PATH = os.path.join(HERE, "results_table.tex")


def best_baseline(cv_results, exclude=("hierboost (LD block-latent + spike-slab)",
                                        "SuSiE credible-set SNPs + logistic")):
    baselines = [r for r in cv_results if r["method"] not in exclude]
    return max(baselines, key=lambda r: r["acc_mean"])


def method_row(cv_results, name):
    for r in cv_results:
        if r["method"] == name:
            return r
    return None


def fmt_pct(x):
    return f"{100 * x:.1f}\\%"


NARRATIVE_ORDER = ["lct", "slc24a5", "darc", "edar", "herc2_oca2", "abcc11",
                    "adh1b", "apol1", "fut2", "slc45a2"]


def build():
    paths = sorted(glob.glob(os.path.join(RESULTS_DIR, "*.json")),
                    key=lambda p: NARRATIVE_ORDER.index(os.path.splitext(os.path.basename(p))[0])
                    if os.path.splitext(os.path.basename(p))[0] in NARRATIVE_ORDER else 999)
    rows = []
    for path in paths:
        with open(path) as f:
            d = json.load(f)
        best = best_baseline(d["cv_results"])
        hb = method_row(d["cv_results"], "hierboost (LD block-latent + spike-slab)")
        susie_row = method_row(d["cv_results"], "SuSiE credible-set SNPs + logistic")
        rows.append(dict(
            label=(d.get("gene") or d["label"]).replace("_", "/"), rsid=d["causal_rsid"],
            contrast=f"{d['pop_a']} vs {d['pop_b']}",
            n=d["n_individuals"], p=d["n_snps"], nblocks=d["n_blocks"],
            best_name=best["method"], best_acc=best["acc_mean"], best_n=best["n_features"],
            hb_acc=hb["acc_mean"] if hb else None, hb_n=hb["n_features"] if hb else None,
            hb_dist=d["hierboost_full"]["dist_bp"],
            susie_acc=susie_row["acc_mean"] if susie_row else None,
            susie_n=susie_row["n_features"] if susie_row else None,
            susie_dist=d["susie_full"]["dist_bp"],
        ))

    lines = [
        "% AUTO-GENERATED by paper/build_results_table.py -- do not hand-edit.",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{All loci run to date. ``Best baseline'' is the best of "
        "L1-logistic/PCA+logistic/linear~SVM/Random~Forest. Distances are from each "
        "method's top-ranked SNP/block to the literature-reported causal/lead variant.}",
        "\\label{tab:results-auto}",
        "\\small",
        "\\begin{tabular}{llrrrrr}",
        "\\toprule",
        "Locus & Contrast & Best baseline & hierboost & hb dist. & SuSiE & SuSiE dist. \\\\",
        "\\midrule",
    ]
    for r in rows:
        hb_str = f"{fmt_pct(r['hb_acc'])} ({r['hb_n']:.1f}f)" if r["hb_acc"] is not None else "n/a"
        hb_dist_str = f"{r['hb_dist']:.0f}bp" if r["hb_dist"] is not None else "n/a"
        susie_str = f"{fmt_pct(r['susie_acc'])} ({r['susie_n']:.1f}f)" if r["susie_acc"] is not None else "n/a"
        susie_dist_str = f"{r['susie_dist']:.0f}bp" if r["susie_dist"] is not None else "n/a"
        lines.append(
            f"{r['label']} & {r['contrast']} & {fmt_pct(r['best_acc'])} "
            f"({r['best_n']:.1f}f) & {hb_str} & {hb_dist_str} & {susie_str} & "
            f"{susie_dist_str} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH} ({len(rows)} loci)")


if __name__ == "__main__":
    build()
